/**
 * The desktop app's live heap is ~30 MB. G1 kept ~90 MB of its own bookkeeping and whatever heap it once grew to; the
 * serial collector with a small young generation stays near the live size (measured at startup, anonymous memory:
 * 510 MB with G1, 445 MB with these flags, 359 MB with fewer malloc arenas on top, see Main.kt).
 */
val desktopMemoryFlags = listOf(
    "-XX:+UseSerialGC", "-Xms24m", "-XX:MaxNewSize=40m", "-Xmx768m",
    "-XX:MinHeapFreeRatio=10", "-XX:MaxHeapFreeRatio=30", "-XX:+UseStringDeduplication",
)

compose.desktop {
    application {
        mainClass = "io.github.velosako3.blossom.MainKt"
        // Debug-only switches forwarded to `./gradlew :composeApp:run`, e.g. -Pblossom.debugPlay="daft punk".
        jvmArgs += desktopMemoryFlags
        jvmArgs += listOf("blossom.debugPlay", "blossom.forceOffline", "blossom.dataDir", "blossom.vlcLog").mapNotNull { key ->
            providers.gradleProperty(key).orNull?.let { "-D$key=$it" }
        }
        // ponytail: no ProGuard; NewPipe, InnerTubeX and vlcj use reflection and would need keep rules first.
        buildTypes.release.proguard { isEnabled.set(false) }
        nativeDistributions {
            appResourcesRootDir.set(vlcjBundler.vlcNativesDirectory)
            targetFormats(TargetFormat.Msi, TargetFormat.Deb, TargetFormat.AppImage)
            packageName = "blossom"
            // From `./gradlew :composeApp:suggestRuntimeModules`, plus service providers it can't see: EC crypto
            // (HTTPS key exchange, LAN pairing), extra charsets and locale data. `blossom --self-check` guards this list.
            modules(
                "java.instrument", "java.management", "java.net.http", "java.sql", "jdk.dynalink", "jdk.httpserver",
                "jdk.security.auth", "jdk.unsupported", "jdk.crypto.ec", "jdk.charsets", "jdk.localedata",
            )
            packageVersion = blossomVersion.substringBefore('-')
            description = "blossom music player"
            vendor = "blossom"
            licenseFile.set(rootProject.file("LICENSE"))
            linux {
                packageName = "blossom"
                iconFile.set(project.file("icons/blossom.png"))
            }
            windows {
                iconFile.set(project.file("icons/blossom.ico"))
                menuGroup = "blossom"
                upgradeUuid = "6b1f0d0e-5c8e-4f0a-9a43-b10550a1b10d"
            }
        }
    }
}

