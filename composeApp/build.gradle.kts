val blossomVersion = providers.gradleProperty("blossom.version").get()

// Client IDs for optional services, from the git-ignored secrets.properties (or the environment in CI). A missing
// value is "" and hides that option. Generated into build/ only, never committed.
val secretKeys = listOf(
    "GOOGLE_OAUTH_DESKTOP_CLIENT_ID", "GOOGLE_OAUTH_DESKTOP_CLIENT_SECRET", "GOOGLE_OAUTH_ANDROID_CLIENT_ID",
    "DROPBOX_APP_KEY", "LASTFM_API_KEY", "LASTFM_API_SECRET", "DISCORD_APPLICATION_ID",
)
val secretValues: Map<String, String> = run {
    val file = rootProject.file("secrets.properties")
    val props = Properties().apply { if (file.isFile) file.reader().use(::load) }
    secretKeys.associateWith { k -> (props.getProperty(k) ?: System.getenv(k)).orEmpty().trim() }
}

// BlossomBuildInfo is generated so the version lives in one place (gradle.properties).
val generateBuildInfo by tasks.registering {
    val out = layout.buildDirectory.dir("generated/buildinfo/kotlin")
    val version = blossomVersion
    val secrets = secretValues
    // CI builds carry their commit and build time so the updater can tell builds apart; local builds have neither
    // and never check.
    val commit = System.getenv("GITHUB_SHA").orEmpty()
    val builtAt = if (commit.isEmpty()) 0L else System.currentTimeMillis()
    // Public releases are built from v* tags; everything else is a test build (and follows test releases too).
    val testBuild = !System.getenv("GITHUB_REF").orEmpty().startsWith("refs/tags/v")
    inputs.property("version", version)
    inputs.property("commit", commit)
    inputs.property("testBuild", testBuild)
    inputs.property("secrets", secrets.hashCode())
    outputs.dir(out)
    doLast {
        val dir = out.get().asFile.resolve("io/github/velosako3/blossom").apply { mkdirs() }
        dir.resolve("BlossomBuildInfo.kt").writeText(
            """
            |// SPDX-License-Identifier: AGPL-3.0-or-later
            |// Generated by composeApp/build.gradle.kts. Do not edit.
            |package io.github.velosako3.blossom
            |
            |object BlossomBuildInfo {
            |    const val VERSION: String = "$version"
            |    const val APP_NAME = "blossom"
            |    const val COMMIT: String = "$commit"
            |    const val BUILT_AT_MS: Long = ${builtAt}L
            |    const val TEST_BUILD: Boolean = $testBuild
            |}
            |""".trimMargin(),
        )
        dir.resolve("BlossomSecrets.kt").writeText(
            buildString {
                appendLine("// SPDX-License-Identifier: AGPL-3.0-or-later")
                appendLine("// Generated by composeApp/build.gradle.kts from secrets.properties. Do not edit, do not commit.")
                appendLine("package io.github.velosako3.blossom")
                appendLine()
                appendLine("internal object BlossomSecrets {")
                for ((k, v) in secrets) {
                    val escaped = v.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")
                    appendLine("    const val $k: String = \"$escaped\"")
                }
                appendLine("}")
            },
        )
    }
}

