import org.jetbrains.compose.ComposePlugin
import org.jetbrains.compose.desktop.application.dsl.TargetFormat

plugins {
    id("blossom.compose")
    id("blossom.desktop.app")
}

val blossomVersion = providers.gradleProperty("blossom.version").get()

// BlossomBuildInfo is generated so the version lives in one place (gradle.properties).
val generateBuildInfo by tasks.registering {
    val out = layout.buildDirectory.dir("generated/buildinfo/kotlin")
    val version = blossomVersion
    inputs.property("version", version)
    outputs.dir(out)
    doLast {
        val dir = out.get().asFile.resolve("io/github/velosako3/blossom").apply { mkdirs() }
        dir.resolve("BlossomBuildInfo.kt").writeText(
            """
            |// SPDX-License-Identifier: AGPL-3.0-or-later
            |// Generated by composeApp/build.gradle.kts. Do not edit.
            |package io.github.velosako3.blossom
            |
            |object BlossomBuildInfo {
            |    const val VERSION: String = "$version"
            |    const val APP_NAME = "blossom"
            |}
            |""".trimMargin(),
        )
    }
}

kotlin {
    sourceSets {
        commonMain {
            kotlin.srcDir(generateBuildInfo)
            dependencies {
                implementation(projects.core.designsystem)
                implementation(projects.core.platform)
                implementation(projects.core.player)
                implementation(projects.source.youtubemusic)
                implementation(projects.feature.home)
                implementation(projects.feature.search)
                implementation(projects.feature.album)
                implementation(projects.feature.artist)
                implementation(projects.feature.nowplaying)
            }
        }
        getByName("desktopMain") {
            kotlin.srcDir(tasks.named("generateVlcBundleLoader"))
        }
        getByName("desktopMain").dependencies {
            implementation(libs.vlcj)
            implementation(ComposePlugin.DesktopDependencies.currentOs)
            implementation(libs.kotlinx.coroutines.swing)
        }
    }
}

compose.desktop {
    application {
        mainClass = "io.github.velosako3.blossom.MainKt"
        nativeDistributions {
            appResourcesRootDir.set(vlcjBundler.vlcNativesDirectory)
            targetFormats(TargetFormat.Msi, TargetFormat.Deb, TargetFormat.AppImage)
            packageName = "blossom"
            packageVersion = blossomVersion.substringBefore('-')
            description = "blossom music player"
            vendor = "blossom"
            licenseFile.set(rootProject.file("LICENSE"))
            linux { packageName = "blossom" }
            windows {
                menuGroup = "blossom"
                upgradeUuid = "6b1f0d0e-5c8e-4f0a-9a43-b10550a1b10d"
            }
        }
    }
}

tasks.matching { it.name == "prepareAppResources" }.configureEach { dependsOn("downloadVlcNatives") }
